package memory

import (
	"errors"
	"strings"
)

// ErrIdentityFact 表示这条内容是在给某个人"起名 / 改称呼"，按设计不写入长期记忆。
//
// 它是**可回灌的错误**：工具会把理由交回模型，让模型改用平台名片称呼对方，
// 而不是让整轮对话失败。
var ErrIdentityFact = errors.New("称呼类信息以平台名片为准，不写入长期记忆")

// identityMarkers 是"这条内容在定义某个人怎么被称呼"的判定词。
//
// 为什么整类禁写：称呼与群名片是**平台事实**——每条消息都已经带着最新的名片，
// history.Item.RenderText 会把它渲染成「名字[QQ号]」交给模型。再抄一份进记忆，
// 得到的只是一份会过期的副本，而且它会在每一轮被回灌，压过平台上的新名片。
//
// 真实事故（2026-10-05，群 1105446935）：群里有人说了句"他是奶味辰辰酱"，
// 这条被写进记忆后一直回灌；本人后来改群名片、又亲自要求改称呼，都推不翻它。
// 根因不只是"没覆盖"：三条称呼分别由三个不同发言人写入，**归属人（subject_id）
// 各不相同**，相似度判定根本不会把它们放在一起比较——所以对这类事实，
// 写入侧的覆盖判定在结构上就救不了，只能在入口挡掉。
//
// 代价：像"我女朋友叫小美"这类事实也会被拒。这是刻意的取舍——把它拒掉会得到
// 一次明确的提示并促使模型改述（"女朋友小美喜欢猫"不会被拒），而放进去就会变成
// 下一个"改不掉的旧名字"。因此判定词取多字词，不用单字"叫"，避免误伤
// "叫你一声""叫我去吃饭"这类普通句子。
var identityMarkers = []string{
	"昵称", "名字", "姓名", "外号", "绰号", "马甲", "备注名",
	"群名片", "名片", "称呼", "叫做", "叫作", "改名为", "改名",
}

// LooksLikeIdentityFact 报告一条记忆正文是否在定义某个人的称呼。
//
// 判定是**保守**的：只认列出的多字词，宁可漏判（放进去一条称呼）也不误伤
// 普通事实（把"张三很怕辣"挡在门外）。漏判的那些会在下一次写入时被
// 同归属人的相似度判定覆盖掉——那是 TieredMemory.Save 的职责。
func LooksLikeIdentityFact(text string) bool {
	trimmed := strings.TrimSpace(text)
	if trimmed == "" {
		return false
	}
	for _, marker := range identityMarkers {
		if strings.Contains(trimmed, marker) {
			return true
		}
	}
	return false
}
